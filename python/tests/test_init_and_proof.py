def test_duplicate_hashes_at_init_are_expected(small_model):
    """Not every tensor has a distinct hash at initialisation, and asserting
    otherwise would be a false invariant.

    17 RMSNorm weights (two per layer plus the final norm) all initialise to
    exactly 1.0, and the two RoPE buffers hold identical values, so 76 tensors
    yield only 59 distinct digests. This is correct behaviour — but it means
    a version diff must compare tensor NAMES, never hash uniqueness, or a
    real change to one norm would be invisible among sixteen identical
    siblings.
    """
    model, _, _ = small_model
    tensors = proof.tensor_hashes(model)["tensors"]
    digests = [t["sha256"] for t in tensors.values()]
    assert len(digests) == 76
    assert len(set(digests)) == 59

    norm_names = [n for n in tensors if n.endswith("norm.weight")]
    assert len(norm_names) == 17  # 8 layers x 2 + final norm
    assert len({tensors[n]["sha256"] for n in norm_names}) == 1

    rope = [n for n in tensors if "inv_freq" in n]
    assert len(rope) == 2
    assert tensors[rope[0]]["sha256"] == tensors[rope[1]]["sha256"]


def test_seed_dependent_and_seed_invariant_tensors(small_model):
    """A precise, surprising split worth knowing before we write the
    training-diff test.

    Of 76 tensors, 57 depend on the seed. The other 19 do not: the 17 RMSNorm
    weights initialise to exactly 1.0 regardless of seed, and the 2 RoPE
    inverse-frequency buffers are a deterministic function of head_dim and
    rope_theta. Those 19 are byte-identical across every random seed.

    This does not threaten `test_every_tensor_differs_after_training` — both
    the norms and the buffers move once gradients reach them. It does mean a
    change-detection test written against *initialisation* would fail on 19 of
    76 tensors, and that "reseeding produces a different brain" holds for 57.
    """
    from sma import arch, proof

    a, _, _ = small_model
    other, _, _ = arch.build_model("small", seed=1)
    ta = proof.tensor_hashes(a)["tensors"]
    tb = proof.tensor_hashes(other)["tensors"]
    assert set(ta) == set(tb)

    changed = {n for n in ta if ta[n]["sha256"] != tb[n]["sha256"]}
    norms = {n for n in ta if n.endswith("norm.weight")}
    rope = {n for n in ta if "inv_freq" in n}
    assert len(norms) == 17  # 8 layers x 2 + final norm
    assert len(rope) == 2

    assert changed == set(ta) - norms - rope
    assert len(changed) == 57


def test_diff_must_be_computed_by_tensor_name(small_model):
    """A name-keyed diff, not a hash-set comparison.

    76 tensors occupy only 59 distinct digests: 17 norms collapse to one and
    2 RoPE buffers to another. Comparing digest sets therefore loses the
    name-to-tensor correspondence entirely — it can report that "something
    changed" but never which tensor, and two norms drifting to the same value
    would be invisible. The manifest is keyed by name precisely so that the
    v001->v002 diff can be read tensor by tensor.
    """
    from sma import arch, proof

    a, _, _ = small_model
    same, _, _ = arch.build_model("small", seed=0)
    other, _, _ = arch.build_model("small", seed=1)

    def changed(ta, tb):
        assert set(ta) == set(tb), "name sets must match before diffing"
        return {n for n in ta if ta[n]["sha256"] != tb[n]["sha256"]}

    ta = proof.tensor_hashes(a)["tensors"]
    ts = proof.tensor_hashes(same)["tensors"]
    to = proof.tensor_hashes(other)["tensors"]

    assert len(ta) == 76
    assert len({t["sha256"] for t in ta.values()}) == 59
    assert changed(ta, ts) == set(), "same seed moves nothing"
    assert len(changed(ta, to)) == 57


def test_tensor_hashes_change_with_seed(small_model):
    a, _, _ = small_model
    b, _, _ = arch.build_model("small", seed=1)
    ha = proof.tensor_hashes(a)["tensors"]["model.embed_tokens.weight"]["sha256"]
