def test_manifest_records_random_initialisation(small_model):
    model, config, sizes = small_model
    m = proof.build_manifest(
        config_name="small",
        version="v001",
        model=model,
        architecture=arch.architecture_report("small"),
        sizes=sizes,
        seed=0,
        dtype="bfloat16",
        structural_audit=proof.audit_from_pretrained_usage(
            Path(__file__).resolve().parents[1] / "sma"
        ),
    )
    assert m["initialisationType"] == "RANDOM"
    assert m["pretrainedWeightsUsed"] is False
    # The fallback records patterns we *requested*; a real fetch records only
    # files that exist upstream. Neither may ever name a weight artifact.
    assert not any(f.endswith(("safetensors", "bin", "pt")) for f in
                   m["configSource"]["filesDownloaded"])
    assert m["configSource"]["weightsDownloaded"] == []
    assert m["configSource"]["weightBytes"] == 0
    assert m["initializer"]["kind"] == proof.INITIALIZER_KIND
    assert m["initializer"]["std"] == 0.02
    assert "pretrained-artifact" in m["tokenizerSource"]
    assert m["sizes"]["parametersUniqueByStorage"] == 61_839_744


def test_manifest_persists_structural_audit_evidence(small_model):
    """The audit must live in the manifest, not only in the console reply.

    An init that printed "0 violations" while writing no evidence would leave
    nothing to re-verify later, which defeats the point of a provenance record.
    """
    model, _, sizes = small_model
    audit = proof.audit_from_pretrained_usage(
        Path(__file__).resolve().parents[1] / "sma"
    )
    assert audit["violations"] == []
    assert audit["calls"], "the audit must actually have scanned something"

    m = proof.build_manifest(
        config_name="small",
        version="v001",
        model=model,
        architecture=arch.architecture_report("small"),
        sizes=sizes,
        seed=0,
        dtype="bfloat16",
        structural_audit=audit,
    )
    assert m["structuralAudit"] == audit
    assert m["structuralAudit"]["violations"] == []


