def test_init_is_deterministic_per_seed():
    torch.manual_seed(0)
    a, _, _ = arch.build_model("small", seed=0)
    b, _, _ = arch.build_model("small", seed=0)
    c, _, _ = arch.build_model("small", seed=1)
    sa, sb, sc = a.state_dict(), b.state_dict(), c.state_dict()
    assert all(torch.equal(sa[k], sb[k]) for k in sa), "same seed must reproduce"
    assert not all(torch.equal(sa[k], sc[k]) for k in sa), "different seed must differ"


def test_init_distribution_matches_initializer_range():
    """transformers 5.x uses a plain normal at std=initializer_range.

    Worth pinning: the docstring says "truncated normal" and the observed
    max is ~4.6 sigma, not 2. If this ever changes, the manifest's recorded
    initializer kind becomes wrong and must be updated with it.
    """
    model, config, _ = arch.build_model("small", seed=0)
    w = model.state_dict()["model.layers.0.mlp.gate_proj.weight"].float()
    assert w.std().item() == pytest.approx(0.02, rel=0.02)
    assert w.mean().item() == pytest.approx(0.0, abs=0.001)
    assert w.abs().max().item() > 0.04, "truncated at 2 sigma would cap near 0.04"


def test_norms_are_ones_and_no_biases(small_model):
    model, _, _ = small_model
    n = model.state_dict()["model.layers.0.input_layernorm.weight"].float()
    assert torch.allclose(n, torch.ones_like(n))
    assert not any(k.endswith("mlp.gate_proj.bias") for k in model.state_dict())


def test_tied_embedding_is_one_parameter():
    """tie_word_embeddings means one tensor, not two. The state dict aliases
    lm_head.weight onto model.embed_tokens.weight; counting entries instead of
    storages would report 111M and mask a real change to the embedding."""
    model, _, _ = arch.build_model("small", seed=0)
    total = sum({p.data_ptr(): p.numel() for p in model.parameters()}.values())
    assert total == 61_839_744
    if "lm_head.weight" in model.state_dict():
        e = model.state_dict()["model.embed_tokens.weight"]
        l = model.state_dict()["lm_head.weight"]
        assert e.untyped_storage().data_ptr() == l.untyped_storage().data_ptr()


