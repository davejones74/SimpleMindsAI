@pytest.mark.slow
def test_real_fetch_downloads_no_weight_bytes(tmp_root):
    """End-to-end against the actual Hub, proving the allowlist holds.

    This is the only test that touches the network, and it asserts on bytes
    rather than filenames: a single shard fetched under any name would show up
    as weightBytes > 0.
    """
    info = proof.fetch_config_and_tokenizer(
        configs.ARCH_REFERENCE_REPO, tmp_root / "ref"
    )
    assert info["weightsDownloaded"] == []
    assert info["weightBytes"] == 0
    assert "config.json" in info["filesDownloaded"]
    assert "tokenizer.json" in info["filesDownloaded"]
    # hub bookkeeping under .cache/ must not pollute the manifest
    assert not any(f.startswith(".cache") for f in info["filesDownloaded"])
    # and the fetched config must be the real published 3B config
    fetched = json.loads(
        (Path(info["localDir"]) / "config.json").read_text(encoding="utf-8")
    )
    for key, value in configs.SMOLLM3_3B_OFFICIAL.items():
        assert fetched[key] == value, f"upstream {key} drifted from our source of truth"


