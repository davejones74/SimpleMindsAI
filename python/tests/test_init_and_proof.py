def test_commit_writes_marker_and_is_atomic(tmp_root):
    with store.staging_dir(tmp_root, "v001") as tmp:
        store.write_json(tmp / "payload.json", {"a": 1})
        assert not (tmp_root / "v001").exists(), "must not be visible before commit"
    assert (tmp_root / "v001").exists()
    assert not store.is_committed(tmp_root / "v001")
    store.commit_marker(tmp_root / "v001", {"note": "test"})
    assert store.is_committed(tmp_root / "v001")
    assert store.read_json(tmp_root / "v001" / "COMMITTED")["note"] == "test"


def test_failed_stage_leaves_no_debris(tmp_root):
    with pytest.raises(RuntimeError):
        with store.staging_dir(tmp_root, "v002") as tmp:
            store.write_json(tmp / "partial.json", {})
            raise RuntimeError("build failed")
    assert not (tmp_root / "v002").exists()
    assert list(tmp_root.glob("*")) == []


def test_versions_are_immutable(tmp_root):
    with store.staging_dir(tmp_root, "v001"):
        pass
    store.commit_marker(tmp_root / "v001")
    with pytest.raises(FileExistsError):
        with store.staging_dir(tmp_root, "v001"):
            pass


def test_version_numbering_never_reuses(tmp_root):
    assert store.next_version(tmp_root) == "v001"
    for v in ("v001", "v002"):
        with store.staging_dir(tmp_root, v):
            pass
        store.commit_marker(tmp_root / v)
    assert store.next_version(tmp_root) == "v003"


