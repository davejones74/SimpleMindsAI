def test_expected_initial_loss_is_log_vocab():
    assert proof.expected_initial_loss(128_256) == pytest.approx(math.log(128_256))
    assert proof.expected_initial_loss(128_256) == pytest.approx(11.7618, abs=1e-4)


def test_loss_signature_guard_rejects_low_loss():
    """A pretrained SmolLM3 scores ~1.8-2.5. If a future vNNN ever evaluates
    that low, a weight leaked — this is the guard that notices."""
    with pytest.raises(AssertionError, match="pretrained weights leaked"):
        proof.check_loss_signature(2.1, 128_256)


def test_loss_signature_guard_rejects_hyperbolic_loss():
    with pytest.raises(AssertionError):
        proof.check_loss_signature(40.0, 128_256)


def test_measured_initial_loss_lands_in_band(small_model, tiny_corpus, tokenizer):
    """The empirical version of the same claim: run a real forward pass on a
    real corpus and confirm the loss is where an untrained model must be.

    This is the check that would catch a silently-pretrained model, because
    nothing else in the pipeline inspects the numbers.
    """
    model, config, _ = small_model
    ids = tokenizer(tiny_corpus, return_tensors="pt").input_ids[:, :128]
    with torch.no_grad():
        out = model(input_ids=ids, labels=ids)
    loss = float(out.loss)
    result = proof.check_loss_signature(loss, config.vocab_size)
    assert result["ok"]
    assert abs(result["deltaFromUniform"]) < 1.0
